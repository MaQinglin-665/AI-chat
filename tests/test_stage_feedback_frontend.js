const assert = require('assert');
const {createController} = require('../web/stageFeedbackController');
const elements = {};
const doc = {getElementById(id) { return elements[id] ||= {hidden:true,dataset:{},textContent:'',addEventListener(k,fn){this[k]=fn;}}; }};
let callback, delay, cancelled;
const feedback = createController({document:doc,schedule(fn,ms){callback=fn;delay=ms;cancelled=false;return 1;},cancel(){cancelled=true;}});
feedback.bind();
let id=feedback.begin(); assert.equal(delay,600); assert(elements['stage-feedback'].hidden);
callback(); assert.equal(elements['stage-feedback-text'].textContent,'正在想…');
feedback.received(id); assert(elements['stage-feedback'].hidden); assert(cancelled);
id=feedback.begin(); feedback.failed(id,new Error('Invalid API token.'));
assert.equal(elements['stage-feedback'].dataset.kind,'auth');
assert(elements['stage-feedback-text'].textContent.includes('访问令牌无效或缺失'));
assert(elements['stage-feedback-text'].textContent.includes('api_token'));
assert(!elements['stage-feedback-doctor'].hidden);
feedback.finish(id); assert(!elements['stage-feedback'].hidden,'error remains available after request finishes');
id=feedback.begin(); feedback.failed(id,new Error('timeout')); assert.equal(elements['stage-feedback'].dataset.kind,'error');
feedback.clear(); assert(elements['stage-feedback'].hidden);
feedback.startupFailure('HTTP 401'); feedback.clear(); feedback.startupFailure('HTTP 500'); assert(elements['stage-feedback'].hidden,'startup warning only once');
const old=feedback.begin(); id=feedback.begin(); feedback.failed(old,'HTTP 401'); assert(elements['stage-feedback'].hidden,'stale requests cannot overwrite the current state');
feedback.received(id);
let opened=false;doc.getElementById('doctor-btn').click=()=>opened=true;elements['stage-feedback-doctor'].click();assert(opened);
const onboarding=require('../web/onboardingController');
const ui={onboardingModal:{hidden:true,classList:{toggle(){}}},chatInput:{focus(){this.focused=true;}},onboardingNextBtn:{},onboardingQuickBtn:{},onboardingDoneBtn:{}};
const state={};const guide=onboarding.createController({state,ui,onboardingSteps:[{title:'chat'},{title:'voice'}]});
guide.openOnboardingModal();assert(ui.chatInput.focused);assert(ui.onboardingQuickBtn.hidden);assert(!ui.onboardingNextBtn.hidden);assert(ui.onboardingDoneBtn.hidden);
guide.moveOnboardingStep(1);assert(ui.onboardingNextBtn.hidden);assert(!ui.onboardingDoneBtn.hidden);
console.log('Stage waiting/error/auth, clearing, startup deduplication, doctor and single-primary onboarding passed.');
