const assert = require('node:assert/strict');
const {createFramePacer, QUALITY, startClock} = require('../web/avatar/vrmRenderer.js');
const p = createFramePacer();
assert.equal(p.step(0,false).fps,60);
assert.equal(p.step(2999,false).fps,60);
assert.equal(p.step(3000,false).fps,25);
p.step(3040,false);
assert.equal(p.step(3041,true).due,true,'wake without waiting for idle interval');
assert.equal(p.step(5000,true).fps,60);
assert.equal(p.step(7999,false).fps,60);
assert.equal(p.step(8000,false).fps,25);
let callback, updates=0;
const state={ttsContextSpeaking:true}, host={document:{hidden:false},requestAnimationFrame:f=>(callback=f,1),cancelAnimationFrame(){},clearTimeout(){}};
const stop=startClock({update:()=>updates++,isAnimating:()=>false},now=>({now,mouth:{open:0}}),{state},host);
for(let i=0;i<600;i++)callback(i*1000/60);
assert.equal(updates,600,'speech silence between syllables must remain 60Hz');
stop();
assert.equal(QUALITY.idleDelayMs,3000);
console.log('VRM adaptive idle/wake and continuous speech cadence passed.');
